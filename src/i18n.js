  const DICT = { en, es };
  // Dificultad (texto de los niveles, en español) → clave. Los niveles no se tocan: se traduce al mostrarla.
  const DIFF_KEY = { 'Fácil': 'easy', 'Normal': 'normal', 'Difícil': 'hard', 'Muy difícil': 'veryhard', 'Demonio': 'demon' };

  function savedLang() {
    try {
      const s = JSON.parse(root.localStorage.getItem(SAVE_KEY));
      return s && DICT[s.lang] ? s.lang : 'en';
    } catch (e) { return 'en'; }
  }
  const hasDom = typeof document !== 'undefined';
  let lang = hasDom && root.localStorage ? savedLang() : 'en';

  function has(key) { return key in DICT[lang] || key in en; }
  function t(key, vars) {
    let s = DICT[lang][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }
  // Nombre y dificultad de un nivel oficial (por id); los del editor llevan el nombre que puso el jugador.
  function levelName(def) { return def && has('lvl.' + def.id) ? t('lvl.' + def.id) : (def && def.name) || ''; }
  function levelDiff(def) { const k = def && DIFF_KEY[def.difficulty]; return k ? t('diff.' + k) : (def && def.difficulty) || ''; }
  // Nombre de una canción real (tracks.js): sólo algunas tienen traducción.
  function trackName(id, fallback) { return has('track.' + id) ? t('track.' + id) : fallback; }

  // Rellena los textos marcados con data-i18n* dentro de el (o de toda la página).
  function apply(el) {
    if (!hasDom) return;
    const r = el || document;
    r.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
    r.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
    r.querySelectorAll('[data-i18n-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.dataset.i18nAria)); });
    r.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
    r.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
    if (!el) {
      document.documentElement.lang = lang;
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.content = t('meta.description');
    }
  }
  function setLang(l) {
    lang = DICT[l] ? l : 'en';
    api.lang = lang;
    apply();
    if (hasDom) root.dispatchEvent(new Event('langchange'));
  }

  const api = { lang, LANGS, t, has, setLang, apply, levelName, levelDiff, trackName };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else {
    root.I18N = api;
    root.t = t;
    if (hasDom) apply();
  }
